def _run_eval_all_tasks(model_name: str) -> str:
    """
    Run evaluation on 30 autogenerated sequences for all 3 tasks.
    Returns formatted metrics string.
    """
    if not model_name:
        return "No model selected."

    model = _get_model(model_name)
    seqs = _load_eval_sequences(n_sequences=30)
    if not seqs:
        return "No data found. Expected *_extended.csv or *_variants.csv in data/raw/."

    lines = [
        "=" * 60,
        f"  EVALUATION — {model_name} — 30 sequences (10 per family)",
        "=" * 60,
        "",
    ]

    # ── Task 1: Next-Step Prediction ──────────────────────────────────────
    top1 = top3 = top5 = total = 0
    rr = 0.0
    for family, steps in seqs:
        n = len(steps)
        # Sample positions between 20% and 80%
        positions = list(range(max(2, n // 5), int(n * 0.8), max(1, n // 10)))
        for pos in positions:
            prefix = steps[:pos]
            true_next = steps[pos]
            preds = model.predict_next(prefix, top_k=5)
            h1 = bool(preds) and preds[0] == true_next
            h3 = true_next in preds[:3]
            h5 = true_next in preds[:5]
            r = 1.0 / (preds.index(true_next) + 1) if true_next in preds else 0.0
            top1 += h1; top3 += h3; top5 += h5; rr += r; total += 1

    lines += [
        "─" * 60,
        "TASK 1 — NEXT-STEP PREDICTION",
        "─" * 60,
        f"  Positions evaluated : {total}",
        f"  Top-1 Accuracy     : {_safe_div(top1, total):.4f}",
        f"  Top-3 Accuracy     : {_safe_div(top3, total):.4f}",
        f"  Top-5 Accuracy     : {_safe_div(top5, total):.4f}",
        f"  MRR                : {_safe_div(rr, total):.4f}",
        "",
    ]

    # ── Task 2: Sequence Completion ───────────────────────────────────────
    ned_all = []; exact_all = []; tacc_all = []; bacc_all = []
    for family, steps in seqs:
        n = len(steps)
        for frac in (0.6, 0.8):
            cut = int(n * frac)
            prefix = steps[:cut]
            ref = steps[cut:]
            if not ref:
                continue
            predicted = model.predict_completion(prefix)
            ned = _levenshtein(predicted, ref) / max(len(predicted), len(ref), 1)
            exact = predicted == ref
            m = min(len(predicted), len(ref))
            tacc = sum(p == r for p, r in zip(predicted, ref)) / m if m else 0.0
            bacc = (sum(p == r for p, r in zip(_block_sig(predicted), _block_sig(ref)))
                    / max(len(_block_sig(ref)), 1))
            ned_all.append(ned); exact_all.append(exact)
            tacc_all.append(tacc); bacc_all.append(bacc)

    def mean(lst):
        return sum(lst) / len(lst) if lst else float("nan")

    lines += [
        "─" * 60,
        "TASK 2 — SEQUENCE COMPLETION",
        "─" * 60,
        f"  Sequences evaluated : {len(ned_all)}",
        f"  Mean NED (↓ better) : {mean(ned_all):.4f}",
        f"  Exact Match Rate    : {mean(exact_all):.4f}  ({sum(exact_all)}/{len(exact_all)})",
        f"  Mean Token Accuracy : {mean(tacc_all):.4f}",
        f"  Mean Block Accuracy : {mean(bacc_all):.4f}",
        "",
    ]

    # ── Task 3: Anomaly Detection ─────────────────────────────────────────
    # Create anomalies by injecting random swaps / deletions into half the seqs
    rng = random.Random(456)
    anomaly_seqs = []
    labels = []

    # Valid sequences (first 15)
    for family, steps in seqs[:15]:
        anomaly_seqs.append(steps)
        labels.append(1)  # valid

    # Invalid sequences (last 15 with injected anomalies)
    for family, steps in seqs[15:30]:
        mutated = list(steps)
        n = len(mutated)
        # Apply 2-3 random mutations
        for _ in range(rng.randint(2, 3)):
            mutation = rng.choice(["swap", "delete", "duplicate"])
            if mutation == "swap" and n > 5:
                i, j = rng.sample(range(2, n - 1), 2)
                mutated[i], mutated[j] = mutated[j], mutated[i]
            elif mutation == "delete" and n > 10:
                idx = rng.randint(2, n - 2)
                mutated.pop(idx)
                n -= 1
            elif mutation == "duplicate" and n > 5:
                idx = rng.randint(2, n - 2)
                mutated.insert(idx, mutated[idx])
                n += 1
        anomaly_seqs.append(mutated)
        labels.append(0)  # invalid

    tp = tn = fp = fn = 0
    pred_scores = []
    for seq, gt_label in zip(anomaly_seqs, labels):
        is_valid, score, rule = model.detect_anomaly(seq)
        pred_label = 1 if is_valid else 0
        pred_scores.append(score)
        if gt_label == 1 and pred_label == 1:
            tn += 1
        elif gt_label == 1 and pred_label == 0:
            fp += 1
        elif gt_label == 0 and pred_label == 0:
            tp += 1
        else:
            fn += 1

    n_total = len(labels)
    accuracy = (tp + tn) / n_total
    prec = _safe_div(tp, tp + fp)
    rec = _safe_div(tp, tp + fn)
    f1 = _safe_div(2 * prec * rec, prec + rec)

    # ROC-AUC
    pos_sc = [s for s, l in zip(pred_scores, labels) if l == 1]
    neg_sc = [s for s, l in zip(pred_scores, labels) if l == 0]
    if pos_sc and neg_sc:
        total_pairs = len(pos_sc) * len(neg_sc)
        conc = sum(p > n for p in pos_sc for n in neg_sc)
        tied = sum(p == n for p in pos_sc for n in neg_sc)
        auc = (conc + 0.5 * tied) / total_pairs
        auc_str = f"{auc:.4f}"
    else:
        auc_str = "n/a"

    lines += [
        "─" * 60,
        "TASK 3 — ANOMALY DETECTION",
        "─" * 60,
        f"  Sequences evaluated : {n_total}  (15 valid + 15 mutated)",
        f"  Binary Accuracy     : {accuracy:.4f}",
        f"  Precision           : {prec:.4f}",
        f"  Recall              : {rec:.4f}",
        f"  F1 Score            : {f1:.4f}",
        f"  ROC-AUC             : {auc_str}",
        f"  Confusion: TP={tp}  FP={fp}  FN={fn}  TN={tn}",
        "",
    ]

    lines += ["=" * 60, "  Evaluation complete.", "=" * 60]
    return "\n".join(lines)


