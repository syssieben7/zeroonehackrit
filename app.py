def _load_eval_sequences(n_sequences: int = 30, seed: int = 123) -> list[tuple[str, list[str]]]:
    """
    Load n_sequences ground truth sequences from extended CSVs (10 per family).
    Returns list of (family, full_step_list).
    """
    rng = random.Random(seed)
    candidates = _EXTENDED_CSVS if any(p.exists() for p in _EXTENDED_CSVS) else _VARIANT_CSVS
    per_family = max(1, n_sequences // 3)
    result = []

    for path in candidates:
        if not path.exists():
            continue
        family = path.stem.split("_")[0].upper()
        seqs: dict[str, list[str]] = {}
        with path.open(newline="", encoding="utf-8-sig") as f:
            for row in csv.DictReader(f):
                sid = row.get("SEQUENCE_ID", "").strip()
                step = row.get("STEP", "").strip()
                if sid and step:
                    seqs.setdefault(sid, []).append(step)

        ids = list(seqs.keys())
        rng.shuffle(ids)
        for sid in ids[:per_family]:
            result.append((family, seqs[sid]))

    return result[:n_sequences]


